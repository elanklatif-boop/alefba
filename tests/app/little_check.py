# Little mode (ages 4 to 6) and tracing sheets: a little one is set up from the welcome, opens straight into big
# letters, traces one and gets a star; grown-ups leave by holding a button; the sheets print one page per letter.
import json
from playwright.sync_api import sync_playwright
res = []
def check(n, ok, x=""): res.append(bool(ok)); print("PASS" if ok else "FAIL", n, "" if ok else x)
URL = "http://127.0.0.1:8811/"
ME = {"talks": True, "plans": True, "signedIn": False}
def ctx(b, vp=(390, 844)):
    c = b.new_context(viewport={"width": vp[0], "height": vp[1]})
    c.route("**/api/**", lambda r: r.fulfill(status=200, content_type="application/json", body=json.dumps(ME)))
    return c
def hold(pg, sel, ms):
    g = pg.locator(sel).bounding_box(); pg.mouse.move(g["x"] + 8, g["y"] + 8); pg.mouse.down(); pg.wait_for_timeout(ms); pg.mouse.up(); pg.wait_for_timeout(200)
def scribble(pg):
    box = pg.locator("#littleCanvas").bounding_box()
    pg.mouse.move(box["x"] + box["width"] * 0.2, box["y"] + box["height"] * 0.5); pg.mouse.down()
    for i in range(30): pg.mouse.move(box["x"] + box["width"] * (0.2 + 0.6 * i / 29), box["y"] + box["height"] * (0.5 + 0.05 * (i % 3)))
    pg.mouse.up()
with sync_playwright() as p:
    b = p.chromium.launch()
    c = ctx(b); pg = c.new_page(); errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(URL); pg.wait_for_timeout(1200)
    pg.click("#obNext"); pg.wait_for_timeout(300)
    check("the welcome offers a little one", pg.is_visible("#obwho-little"))
    pg.click("#obwho-little"); pg.click("#obNext"); pg.wait_for_timeout(300)
    check("then asks the little one's name", "little one called" in pg.inner_text("#onboard"))
    pg.fill("#obName", "Dara"); pg.click("#obNext"); pg.wait_for_timeout(600)
    prof = pg.evaluate("S.profile")
    check(f"and opens little mode, with no level check ({prof})", pg.is_visible("#little") and prof.get("little") is True and prof.get("name") == "Dara")
    check("all 32 letters as big tiles", pg.locator(".little-tile").count() == 32)
    check("no English to read on the letters", all(len(t.strip()) <= 3 for t in pg.locator(".little-tile .g").all_inner_texts()))
    check("tiles go from right to left", pg.get_attribute(".little-unit", "dir") == "rtl")
    pg.click("#lt-be"); pg.wait_for_timeout(500)
    check("a letter: the letter, its picture word and a space to trace", pg.is_visible("#littleBig") and pg.is_visible("#littlePic") and pg.is_visible("#littleCanvas"))
    check("the picture word starts with the letter", pg.inner_text("#littlePic").strip().endswith("بابا"))
    pg.click("#littleOk"); pg.wait_for_timeout(200)
    check("checking an empty drawing doesn't give a star", pg.inner_text("#littleStars").strip().endswith("0") and pg.is_visible("#littleOk"))
    scribble(pg); pg.click("#littleOk"); pg.wait_for_timeout(500)
    check("tracing it gives a star and the next letter is shown", pg.inner_text("#littleStars").strip().endswith("1") and "pulse" in pg.get_attribute("#littleNext", "class") and not pg.is_visible("#littleOk"))
    check("and counts as practising today", pg.evaluate("S.days.includes(todayStr())"))
    pg.click("#littleNext", force=True); pg.wait_for_timeout(300)
    check("the next letter is pe", pg.inner_text("#littleBig").strip() == "پ")
    pg.click("#littleHome"); pg.wait_for_timeout(300)
    check("back home, be has its star", pg.locator("#lt-be .star").count() == 1)
    pg.click("#littleGrown"); pg.wait_for_timeout(300)
    check("a quick tap on Grown-ups does nothing", not pg.is_visible("#littleBackBtn"))
    hold(pg, "#littleGrown", 400)
    check("a short press does nothing either", not pg.is_visible("#littleBackBtn"))
    hold(pg, "#littleGrown", 1500)
    check("holding it opens the grown-ups' page", pg.is_visible("#littleBackBtn") and "1 of 32" in pg.inner_text("#littleMain"))
    pg.click("#littleFullBtn"); pg.wait_for_timeout(400)
    check("Open the full app leaves little mode", pg.is_hidden("#little") and pg.is_visible("#littleCard"))
    pg.reload(); pg.wait_for_timeout(1300)
    check("next visit opens little mode again", pg.is_visible("#little"))
    hold(pg, "#littleGrown", 1500); pg.click("#littleOffBtn"); pg.wait_for_timeout(400)
    check("Turn off little mode turns it off", pg.is_hidden("#little") and pg.evaluate("S.profile.little") is False and pg.locator("#littleCard").count() == 0)
    pg.evaluate("showView('review')"); pg.wait_for_timeout(200)
    pg.click("#who-little"); pg.wait_for_timeout(400)
    check("settings can turn it back on", pg.is_visible("#little") and pg.evaluate("S.profile.little") is True)
    check("no page errors", not errs, errs)
    c.close()

    # tracing sheets, from the Letters tab
    c = ctx(b, (1100, 900)); pg = c.new_page(); errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(URL); pg.wait_for_timeout(1200); pg.evaluate("closeOnboarding()")
    pg.evaluate("showView('library'); setLibPart('alphabet')"); pg.wait_for_timeout(300)
    check("the Letters tab has Print tracing sheets", pg.is_visible("#alphaSheets"))
    pg.click("#alphaSheets"); pg.wait_for_timeout(400)
    check("it starts with the first unit picked", pg.inner_text(".sheet-count").startswith("5 letters") and pg.locator("#sheetPreview .sheet-page").count() == 5)
    pg.click("#sheetUnit-1"); pg.wait_for_timeout(200)
    check("a unit adds its letters", pg.inner_text(".sheet-count").startswith("9 letters"))
    pg.click("#sheetL-alef"); pg.wait_for_timeout(200)
    check("a letter can be taken off", pg.inner_text(".sheet-count").startswith("8 letters") and pg.get_attribute("#sheetL-alef", "aria-pressed") == "false")
    page1 = pg.locator("#sheetPreview .sheet-page").first
    check("a page: dotted letters, joined shapes and the word", page1.locator(".sl-row").count() == 4 and page1.locator("svg text").count() >= 11 and "بابا" in page1.inner_text())
    pg.uncheck("#sheetOpt-forms"); pg.wait_for_timeout(200)
    check("joined shapes can be left out", pg.locator("#sheetPreview .sheet-page").first.locator(".sl-row").count() == 3)
    pg.click("#sheetNone"); pg.wait_for_timeout(200)
    check("with nothing picked, Print is off", pg.is_disabled("#sheetsPrint"))
    pg.click("#sheetAll"); pg.wait_for_timeout(300)
    pg.evaluate("window.__printed = 0; window.print = () => { window.__printed++; }; 0")
    pg.click("#sheetsPrint"); pg.wait_for_timeout(300)
    check("Print puts 32 pages in the print area and prints", pg.locator("#printSheets .sheet-page").count() == 32 and pg.evaluate("window.__printed") == 1)
    pg.emulate_media(media="print"); pg.wait_for_timeout(200)
    check("when printing, only the sheets show", pg.is_visible("#printSheets .sheet-page") and not pg.is_visible("#sheets"))
    pg.emulate_media(media="screen")
    check("no page errors", not errs, errs)
    c.close()

    # easy to find: from the welcome screen, and from links a teacher can share
    c = ctx(b); pg = c.new_page(); errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(URL); pg.wait_for_timeout(1200)
    check("the welcome shows little mode and the teachers' page", pg.is_visible("#obLittleBtn") and pg.is_visible("#obTeachersBtn") and pg.get_attribute("#obTeachersBtn", "href") == "teachers.html")
    pg.screenshot(path="/tmp/claude-0/-home-claude/b7b836a8-070c-54c2-99a3-2a27892ac005/scratchpad/little/welcome.png", full_page=True)
    pg.click("#obLittleBtn"); pg.wait_for_timeout(300)
    check("Ages 4 to 6? goes straight to the name", pg.is_visible("#obName") and "little one called" in pg.inner_text("#onboard"))
    c.close()
    c = ctx(b); pg = c.new_page(); pg.goto(URL + "#little"); pg.wait_for_timeout(1300)
    check("learnalefba.com/#little starts little mode", pg.is_visible("#obName") and "little one called" in pg.inner_text("#onboard"))
    c.close()
    c = ctx(b); pg = c.new_page(); pg.goto(URL + "#sheets"); pg.wait_for_timeout(1300)
    check("learnalefba.com/#sheets opens the tracing sheets", pg.is_visible("#sheetsPrint"))
    check("no page errors", not errs, errs)
    c.close(); b.close()
print(f"{sum(res)} of {len(res)} passed")

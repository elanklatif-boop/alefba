// Usage totals: the app's events become daily totals, unknown events are ignored, and the stats page needs STATS_KEY.
import { D1 } from "./d1shim.mjs";
const SITE = process.env.SITE || "/home/claude/alefba/alefba-site";
const worker = (await import(SITE + "/_worker.js?v=" + Date.now())).default;
const db = new D1(), ASSETS = { fetch: async () => new Response("asset") };
const env = (x = {}) => ({ DB: db, ASSETS, ...x });
let pass = 0, fail = 0;
const check = (n, ok, x = "") => { ok ? pass++ : fail++; console.log((ok ? "PASS " : "FAIL ") + n + (ok ? "" : " " + JSON.stringify(x))); };
let ip = 0;
const call = async (e, path, { method = "GET", body, origin = "https://learnalefba.com" } = {}) => {
  const h = new Headers({ "CF-Connecting-IP": "10.0.0." + (++ip) });
  if (body !== undefined) h.set("content-type", "application/json");
  if (method === "POST" && origin) h.set("Origin", origin);
  const r = await worker.fetch(new Request("https://learnalefba.com" + path, { method, headers: h, body: body === undefined ? undefined : JSON.stringify(body) }), e, { waitUntil: p => p });
  return { status: r.status, text: await r.text(), type: r.headers.get("content-type") };
};
const today = new Date().toISOString().slice(0, 10);
let r = await call(env(), "/api/usage", { method: "POST", body: { e: ["open", "new", "open_child", "lesson_start", "lesson_start", "lesson_done", "hacked", 5, "<b>"], d: today } });
check("events are accepted", r.status === 200, r);
const rows = await db.prepare("SELECT name, n FROM usage WHERE day = ? ORDER BY name").bind(today).all();
const got = Object.fromEntries(rows.results.map(x => [x.name, x.n]));
check(`totals by name ${JSON.stringify(got)}`, got.open === 1 && got.new === 1 && got.lesson_start === 2 && got.lesson_done === 1 && !got.hacked && Object.keys(got).length === 5, got);
await call(env(), "/api/usage", { method: "POST", body: { e: ["open", "back_1"], d: today } });
const open = await db.prepare("SELECT n FROM usage WHERE day = ? AND name = 'open'").bind(today).first("n");
check("a second visit adds to the total", open === 2, open);
r = await call(env(), "/api/usage", { method: "POST", body: { e: ["open"], d: "2001-01-01" } });
const far = await db.prepare("SELECT COUNT(*) AS c FROM usage WHERE day = '2001-01-01'").first("c");
check("a date far from today is replaced by today", far === 0, far);
r = await call(env(), "/api/usage", { method: "POST", body: { e: ["open"] }, origin: "https://evil.example" });
check("another website can't add to the totals", r.status === 403, r.status);
r = await call(env(), "/api/usage", { method: "POST", body: { e: Array(50).fill("lesson_done") } });
const ld = await db.prepare("SELECT n FROM usage WHERE day = ? AND name = 'lesson_done'").bind(today).first("n");
check("at most 20 events at a time", ld === 21, ld);
r = await call(env(), "/stats");
check("no STATS_KEY set: the page doesn't exist", r.status === 404, r.status);
const K = { STATS_KEY: "a-long-secret-123456" };
r = await call(env(K), "/stats");
check("learnalefba.com/stats shows a password box", r.status === 200 && r.text.includes('type="password"') && !r.text.includes("Lessons finished"), r.status);
r = await call(env(K), "/stats/");
check("so does learnalefba.com/stats/ (with the last slash), not the app", r.status === 200 && r.text.includes('type="password"') && r.text !== "asset", r.text.slice(0, 80));
const post = (e, key, origin = "https://learnalefba.com") => {
  const h = new Headers({ "CF-Connecting-IP": "10.0.1." + (++ip), "content-type": "application/x-www-form-urlencoded" });
  if (origin) h.set("Origin", origin);
  return worker.fetch(new Request("https://learnalefba.com/stats", { method: "POST", headers: h, body: "key=" + encodeURIComponent(key) }), e, { waitUntil: p => p }).then(async x => ({ status: x.status, text: await x.text() }));
};
r = await post(env(K), "wrong-guess-000000");
check("the wrong password: the box again, with a message", r.status === 403 && r.text.includes("not the password") && !r.text.includes("Lessons finished"), r.status);
r = await post(env(K), "a-long-secret-123456");
check("the right password shows the numbers", r.status === 200 && r.text.includes("Lessons finished") && r.text.includes(today), r.status);
check("and the totals", /Last 30 days<\/td><td>3<\/td>/.test(r.text), r.text.slice(r.text.indexOf("Last 30"), r.text.indexOf("Last 30") + 80));
// the first lesson, card by card
await call(env(), "/api/usage", { method: "POST", body: { e: ["first_new_1", "first_new_1", "first_new_1", "first_new_1", "first_new_2", "first_new_2", "first_new_3", "first_new_done", "first_new_left", "first_heard_1", "first_new_13", "first_x_1"], d: today } });
const fr = Object.fromEntries((await db.prepare("SELECT name, n FROM usage WHERE day = ? AND name LIKE 'first_%'").bind(today).all()).results.map(x => [x.name, x.n]));
check(`first-lesson cards are counted, and only cards 1 to 12 of the three kinds ${JSON.stringify(fr)}`, fr.first_new_1 === 4 && fr.first_new_2 === 2 && fr.first_new_done === 1 && fr.first_new_left === 1 && fr.first_heard_1 === 1 && !fr.first_new_13 && !fr.first_x_1, fr);
r = await post(env(K), "a-long-secret-123456");
const ft = r.text.slice(r.text.indexOf("Where people stop"));
check("the stats page shows where people stop in their first lesson", ft.includes("Got to card 1</td><td>4 (100%) <small>alef</small></td><td>1 (100%) <small>hear bâbâ</small></td><td>0</td>") && ft.includes("Got to card 2</td><td>2 (50%) <small>be</small>") && ft.includes("Finished it</td><td>1 (25%)</td>") && ft.includes("Got to card 8</td>") && !ft.includes("Got to card 9</td>"), ft.slice(0, 900));
// the welcome's link for those who speak some, and a page that hit an error: counted and shown
await call(env(), "/api/usage", { method: "POST", body: { e: ["ob_heard", "page_error", "page_error", "play_link"], d: today } });
r = await post(env(K), "a-long-secret-123456");
const hd = r.text.slice(0, r.text.indexOf("</tr>")), cells = hd.match(/<th>[^<]*<\/th>/g).map(t => t.slice(4, -5));
const row = r.text.slice(r.text.indexOf(`<td>${today}</td>`)), vals = row.slice(0, row.indexOf("</tr>")).match(/<td>[^<]*<\/td>/g).map(t => t.slice(4, -5));
check(`the stats page has "Hit an error" (2) and "Welcome: Already speak some" (1)`, vals[cells.indexOf("Hit an error")] === "2" && vals[cells.indexOf("Welcome: Already speak some")] === "1", [cells.indexOf("Hit an error"), vals.slice(0, 6)]);
check(`the stats page has the classroom game link (1)`, vals[cells.indexOf("Classroom game link (learnalefba.com/play): opened")] === "1", cells.indexOf("Classroom game link (learnalefba.com/play): opened"));
check("the first-lesson columns say how people started", ft.includes("<th>Start learning (new to Persian)</th><th>Already speak some Persian</th>"), ft.slice(0, 400));
r = await post(env(K), "a-long-secret-123456", "https://evil.example");
check("not from another website", r.status === 403 && !r.text.includes("Lessons finished"), r.status);
r = await call(env(K), "/api/stats?key=a-long-secret-123456");
check("the password in the address no longer works (it would end up in history and searches)", !r.text.includes("Lessons finished"), r.status);
r = await call(env(), "/api/usage", { method: "GET" });
check("counting only takes POST", r.status === 405, r.status);
console.log(`${pass} of ${pass + fail} passed`);
process.exit(fail ? 1 : 0);

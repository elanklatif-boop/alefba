// Usage totals: the app's events become daily totals, unknown events are ignored, and the stats page needs STATS_KEY.
import { D1 } from "./d1shim.mjs";
const SITE = process.env.SITE || "/home/claude/alefba/alefba-site";
const worker = (await import(SITE + "/_worker.js?v=" + Date.now())).default;
const db = new D1(), ASSETS = { fetch: async () => new Response("asset") };
const env = (x = {}) => ({ DB: db, ASSETS, ...x });
let pass = 0, fail = 0;
const check = (n, ok, x = "") => { ok ? pass++ : fail++; console.log((ok ? "PASS " : "FAIL ") + n + (ok ? "" : " " + JSON.stringify(x))); };
let ip = 0;
const call = async (e, path, { method = "GET", body, origin = "https://learnalefba.com" } = {}) => {
  const h = new Headers({ "CF-Connecting-IP": "10.0.0." + (++ip) });
  if (body !== undefined) h.set("content-type", "application/json");
  if (method === "POST" && origin) h.set("Origin", origin);
  const r = await worker.fetch(new Request("https://learnalefba.com" + path, { method, headers: h, body: body === undefined ? undefined : JSON.stringify(body) }), e, { waitUntil: p => p });
  return { status: r.status, text: await r.text(), type: r.headers.get("content-type") };
};
const today = new Date().toISOString().slice(0, 10);
let r = await call(env(), "/api/usage", { method: "POST", body: { e: ["open", "new", "open_child", "lesson_start", "lesson_start", "lesson_done", "hacked", 5, "<b>"], d: today } });
check("events are accepted", r.status === 200, r);
const rows = await db.prepare("SELECT name, n FROM usage WHERE day = ? ORDER BY name").bind(today).all();
const got = Object.fromEntries(rows.results.map(x => [x.name, x.n]));
check(`totals by name ${JSON.stringify(got)}`, got.open === 1 && got.new === 1 && got.lesson_start === 2 && got.lesson_done === 1 && !got.hacked && Object.keys(got).length === 5, got);
await call(env(), "/api/usage", { method: "POST", body: { e: ["open", "back_1"], d: today } });
const open = await db.prepare("SELECT n FROM usage WHERE day = ? AND name = 'open'").bind(today).first("n");
check("a second visit adds to the total", open === 2, open);
r = await call(env(), "/api/usage", { method: "POST", body: { e: ["open"], d: "2001-01-01" } });
const far = await db.prepare("SELECT COUNT(*) AS c FROM usage WHERE day = '2001-01-01'").first("c");
check("a date far from today is replaced by today", far === 0, far);
r = await call(env(), "/api/usage", { method: "POST", body: { e: ["open"] }, origin: "https://evil.example" });
check("another website can't add to the totals", r.status === 403, r.status);
r = await call(env(), "/api/usage", { method: "POST", body: { e: Array(50).fill("lesson_done") } });
const ld = await db.prepare("SELECT n FROM usage WHERE day = ? AND name = 'lesson_done'").bind(today).first("n");
check("at most 20 events at a time", ld === 21, ld);
r = await call(env(), "/api/stats?key=whatever");
check("no STATS_KEY set: the page doesn't exist", r.status === 404, r.status);
const K = { STATS_KEY: "a-long-secret-123456" };
r = await call(env(K), "/api/stats?key=wrong-guess-000000");
check("the wrong key: not found", r.status === 404, r.status);
r = await call(env(K), "/api/stats?key=a-long-secret-123456");
check("the right key shows the page", r.status === 200 && /text\/html/.test(r.type) && r.text.includes("Lessons finished") && r.text.includes(today), r.status);
check("and the totals", /Last 30 days<\/td><td>3<\/td>/.test(r.text), r.text.slice(r.text.indexOf("Last 30"), r.text.indexOf("Last 30") + 80));
r = await call(env(), "/api/usage", { method: "GET" });
check("counting only takes POST", r.status === 405, r.status);
console.log(`${pass} of ${pass + fail} passed`);
process.exit(fail ? 1 : 0);
